<script setup>
import { ref, reactive } from 'vue'
import { authorService } from '@/services/authorService'

const formData = reactive({
  name: '',
  email: '',
  phone: '',
  city: '',
  experience: '',
  portfolio: '',
  motivation: '',
  agreeTerms: false
})

const submitting = ref(false)
const showSuccess = ref(false)

const handleSubmit = async () => {
  submitting.value = true

  try {
    // TODO: Отправка заявки на сервер
    // await authorService.submitApplication(formData)

    // Имитация отправки
    await new Promise(resolve => setTimeout(resolve, 1000))

    // Показываем сообщение об успехе
    showSuccess.value = true

    // Сбрасываем форму
    Object.keys(formData).forEach(key => {
      formData[key] = key === 'agreeTerms' ? false : ''
    })

    // Прокручиваем к сообщению
    setTimeout(() => {
      document.querySelector('.success-message')?.scrollIntoView({
        behavior: 'smooth',
        block: 'center'
      })
    }, 100)

    // Скрываем сообщение через 10 секунд
    setTimeout(() => {
      showSuccess.value = false
    }, 10000)
  } catch (error) {
    console.error('Error submitting application:', error)
    alert('Произошла ошибка при отправке заявки. Пожалуйста, попробуйте снова.')
  } finally {
    submitting.value = false
  }
}
</script>

